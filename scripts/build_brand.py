"""Write napari_sphinx_theme/static/brand/pygments.css.

The brand folder's code colours, for napari sites built without Sphinx:
the theme's "napari" Pygments style in light mode and Pygments' "dracula"
in dark mode, the pair napari.org uses (pygments_light_style and
pygments_dark_style in napari/docs). The dark rules follow the same
selectors as napari-tokens.css.

The output is committed; tests/test_brand.py fails if it is stale. Run
this after changing napari_code_theme.py:

    uv run --no-project --with pygments python scripts/build_brand.py
"""

from __future__ import annotations

import sys
from pathlib import Path

from pygments.formatters import HtmlFormatter  # type: ignore[import-untyped]

ROOT = Path(__file__).parent.parent
OUT = ROOT / "napari_sphinx_theme" / "static" / "brand" / "pygments.css"

# The theme from this checkout, not an installed copy.
sys.path.insert(0, str(ROOT))
from napari_sphinx_theme.napari_code_theme import NapariCodeTheme  # noqa: E402

# Same as napari-tokens.css: the OS's dark mode unless the page chose light,
# or a page that chose dark.
DARK_BY_OS = ":root:not([data-theme='light']):not(.light)"
DARK_BY_PAGE = ("html[data-theme='dark']", "html.dark")


def style_rules(style: object, scopes: list[str]) -> str:
    """Pygments' CSS for a style, with every .highlight rule under each scope.

    With a scope, Pygments' global rules (pre line height, line numbers) are
    dropped: they aren't scoped, so a dark copy would apply in light mode.
    """
    selectors = [f"{scope} .highlight" if scope else ".highlight" for scope in scopes]
    css: str = HtmlFormatter(style=style).get_style_defs(selectors)
    if any(scopes):
        css = "\n".join(line for line in css.splitlines() if ".highlight" in line)
    return css


def pygments_css() -> str:
    light = style_rules(NapariCodeTheme, [""])
    dark_by_os = style_rules("dracula", [DARK_BY_OS])
    dark_by_page = style_rules("dracula", list(DARK_BY_PAGE))
    indented = "\n".join(f"  {line}" for line in dark_by_os.splitlines())
    return (
        "/* napari code colours for sites without Sphinx. Generated by\n"
        "   scripts/build_brand.py: do not edit. Light: the napari style;\n"
        "   dark: dracula, as on napari.org. Wrap code in .highlight. */\n\n"
        f"{light}\n\n"
        f"@media (prefers-color-scheme: dark) {{\n{indented}\n}}\n\n"
        f"{dark_by_page}\n"
    )


def main() -> None:
    OUT.write_text(pygments_css(), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")  # noqa: T201 (a command-line script)


if __name__ == "__main__":
    main()
